#!/usr/bin/env python3
"""Add the home page's canonical, share tags and structured data, and keep the
town chips and service card titles pointing at the right pages.

Fully re-runnable. The generated head block sits between markers and is
replaced wholesale, and the town chip list is rebuilt from build.TOWNS, so
changing the towns means editing build.py and running both scripts -- nothing
is left behind holding a stale town name.

Run from the project root, after build.py:  python seo_home.py
"""
import json
import re
import sys

import build

START = '<!-- generated by seo_home.py - do not hand edit -->'
END = '<!-- end generated -->'
NL = '\r\n'

SITE = build.SITE
BIZ = build.BIZ
DESC = ('Soft wash and pressure washing across South Jersey - shore towns and mainland. '
        'House, roof, deck, drive and gutter cleaning. Quote your job and book online '
        'in minutes.')

# Towns that get their own page, plus places that ride along with one.
EXTRA_CHIPS = [('Marmora', 'upper-township')]

t = open('index.html', 'rb').read().decode('utf-8')
log = []

# ----------------------------------------------------------- head block
ld = {'@context': 'https://schema.org', '@graph': [
    build.ld_business(),
    {'@type': 'WebSite', '@id': SITE + '/#website', 'url': SITE + '/',
     'name': BIZ, 'publisher': {'@id': SITE + '/#business'}},
]}
block = NL.join([
    START,
    '<link rel="canonical" href="%s/">' % SITE,
    '<meta property="og:type" content="website">',
    '<meta property="og:site_name" content="%s">' % BIZ,
    '<meta property="og:title" content="%s | Pressure Washing &amp; Soft Wash in South Jersey">' % BIZ,
    '<meta property="og:description" content="%s">' % DESC,
    '<meta property="og:url" content="%s/">' % SITE,
    '<meta property="og:image" content="%s/img/house-washing.jpg">' % SITE,
    '<meta name="twitter:card" content="summary_large_image">',
    '<script type="application/ld+json">'
    + json.dumps(ld, indent=None, separators=(',', ':')) + '</script>',
    END,
])

if START in t:
    t = re.sub(re.escape(START) + '.*?' + re.escape(END), lambda m: block, t, count=1, flags=re.S)
    log.append('refreshed head block (canonical, Open Graph, structured data)')
else:
    # first run, or upgrading from the unmarked version
    old = re.search(r'<link rel="canonical".*?</script>', t, re.S)
    if old:
        t = t[:old.start()] + block + t[old.end():]
        log.append('replaced the unmarked head block with a marked one')
    else:
        anchor = '<!-- Tracking: add Osprey'
        i = t.find(anchor)
        if i < 0:
            print('!! could not find the head insertion point')
            sys.exit(1)
        t = t[:i] + block + NL + t[i:]
        log.append('inserted head block (canonical, Open Graph, structured data)')

# ------------------------------------------------------- town chip list
chips = [(x['name'], x['slug']) for x in build.TOWNS] + EXTRA_CHIPS
chips.sort(key=lambda c: c[0])
markup = NL.join('        <a class="city-tag" href="%s.html">%s</a>' % (slug, name)
                 for name, slug in chips)
m = re.search(r'(<div class="area-cities">)(.*?)(\s*</div>)', t, re.S)
if not m:
    print('!! could not find the service area chip list')
    sys.exit(1)
t = t[:m.start()] + m.group(1) + NL + markup + NL + '      </div>' + t[m.end():]
log.append('rebuilt the service area chips (%d towns)' % len(chips))

# ------------------------------------------------- the services grid
m = re.search(r'<div class="services-grid">.*?\r?\n  </div>\r?\n</section>', t, re.S)
if not m:
    print('!! could not find the services grid')
    sys.exit(1)
t = t[:m.start()] + build.service_cards_html() + '\r\n</section>' + t[m.end():]
log.append('rebuilt the services grid (%d cards, whole card clickable)' % len(build.SERVICES))

# ------------------------------------------------ styles for those links
CSS_START = '/* === generated by seo_home.py === */'
CSS_ADD = CSS_START + """
/* Town chips link to their town pages. */
a.city-tag{text-decoration:none;display:inline-block}
a.city-tag:hover{border-color:var(--sky);color:var(--ink)}

/* The whole service card is the link, not just the title: a title-only link
   gave no hint of where to click and most people never reached the pages. */
a.svc-card{display:block;text-decoration:none;color:inherit;cursor:pointer}
a.svc-card:focus-visible{outline:3px solid var(--sky);outline-offset:3px}
.svc-more{margin-top:13px;font-size:.85rem;font-weight:700;color:var(--ocean);display:flex;align-items:center;gap:6px}
.svc-more .arw{transition:transform .2s}
a.svc-card:hover .svc-more{color:var(--ink)}
a.svc-card:hover .svc-more .arw{transform:translateX(5px)}

/* Fallback tile for a service with no photo yet - looks deliberate rather
   than broken, and swaps straight out when a photo arrives. */
.svc-img.ph{display:flex;align-items:center;justify-content:center;background:linear-gradient(150deg,var(--ink) 0%,#17505a 100%)}
.svc-img.ph span{font-size:3.1rem;line-height:1;filter:saturate(.9)}
"""
css = open('css/site.css', encoding='utf-8').read()
if CSS_START in css:
    css = css[:css.index(CSS_START)]
    open('css/site.css', 'w', encoding='utf-8', newline='\r\n').write(css.rstrip() + '\r\n\r\n' + CSS_ADD)
    log.append('refreshed the generated stylesheet block')
else:
    # first run under the marked scheme: drop the older unmarked additions
    old = '\n/* town chips and service titles became links when the sub-pages were added */'
    if old in css:
        css = css[:css.index(old)]
        open('css/site.css', 'w', encoding='utf-8', newline='\r\n').write(css.rstrip() + '\r\n\r\n' + CSS_ADD)
        log.append('replaced the unmarked stylesheet additions with a marked block')
    else:
        open('css/site.css', 'a', encoding='utf-8', newline='\r\n').write('\r\n' + CSS_ADD)
        log.append('added the generated stylesheet block')

open('index.html', 'wb').write(t.encode('utf-8'))
print('home page:')
for x in log:
    print('  -', x)
